"""Build the hand-written J1939 capture fixtures and expected results.

The scenarios below are spelled out frame by frame rather than generated by
the production reassembler: every CAN identifier is composed from explicit
bit fields, every payload is an explicit byte string, and the expected
outputs (states, per-window flow control, packet provenance and payload
bytes) are written into ``j1939-expected.json`` so an independent verifier
can check the real database byte by byte without trusting this builder.

Usage:  python3 -I tools/build_j1939_fixtures.py
"""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist" / "j1939"

SRC = 0x10          # diagnostic sender
R1 = 0x20           # first receiver
R2 = 0x30           # second receiver
GLOBAL = 0xFF
PGN_TP_CM = 0x00EC00
PGN_TP_DT = 0x00EB00
APP_PGN = 0x00F004
BUS_A = "can-alpha"
BUS_B = "can-beta"

DATA_GAP_NS = 100
CONTROL_GAP_NS = 50


def can_id(priority: int, edp: int, dp: int, pf: int, ps: int, sa: int) -> int:
    return ((priority << 26) | (edp << 25) | (dp << 24)
            | (pf << 16) | (ps << 8) | sa)


def cm_id(src: int, dst: int) -> int:
    # TP.CM is PDU1: PF=0xEC and PS is the destination address.
    return can_id(6, 0, 0, 0xEC, dst, src)


def dt_id(src: int, dst: int) -> int:
    # TP.DT shares the PDU1 addressing shape (PF=0xEB).
    return can_id(6, 0, 0, 0xEB, dst, src)


def cm(control: int, b2: int = 0, b3: int = 0, b4: int = 0, b5: int = 0,
       pgn: int = APP_PGN) -> bytes:
    return bytes([control, b2, b3, b4, b5,
                  pgn & 0xFF, (pgn >> 8) & 0xFF, (pgn >> 16) & 0xFF])


def rts(size: int, packets: int, max_cts: int, pgn: int = APP_PGN) -> bytes:
    return cm(0x10, size & 0xFF, size >> 8, packets, max_cts, pgn)


def bam(size: int, packets: int, pgn: int = APP_PGN) -> bytes:
    return cm(0x20, size & 0xFF, size >> 8, packets, 0xFF, pgn)


def cts(count: int, start: int, pgn: int = APP_PGN) -> bytes:
    return cm(0x11, count, start, 0xFF, 0xFF, pgn)


def eom_ack(size: int, packets: int, pgn: int = APP_PGN) -> bytes:
    return cm(0x13, size & 0xFF, size >> 8, packets, 0xFF, pgn)


def abort(reason: int, pgn: int = APP_PGN) -> bytes:
    return cm(0xFF, reason, 0xFF, 0xFF, 0xFF, pgn)


def dt(seq: int, chunk: bytes) -> bytes:
    assert 1 <= len(chunk) <= 7
    return bytes([seq]) + chunk + b"\x00" * (7 - len(chunk))


class Timeline:
    """Accumulates (bus, timestamp_ns, can_id, data) rows with an explicit clock."""

    def __init__(self) -> None:
        self.rows: list[tuple[str, int, int, bytes]] = []
        self.t: int | None = None

    def at(self, bus: str, ts: int, ident: int, data: bytes) -> None:
        if self.t is not None:
            assert ts >= self.t, "timeline must be non-decreasing"
        self.t = ts
        self.rows.append((bus, ts, ident, data))

    def advance(self, bus: str, delta: int, ident: int, data: bytes) -> None:
        assert self.t is not None
        self.at(bus, self.t + delta, ident, data)


def ordinary_frame(src: int, dst: int, payload: bytes,
                   pgn: int = 0x00FEEE) -> tuple[int, bytes]:
    # PDU2 ordinary frame: PF=0xFE >= 240, PS becomes part of the PGN.
    ps = pgn & 0xFF
    pf = (pgn >> 8) & 0xFF
    return can_id(6, 0, pgn >> 16, pf, ps, src), payload + b"\x00" * (8 - len(payload))


def write_capture(path: Path, rows: list[tuple[str, int, int, bytes]]) -> None:
    buf = io.StringIO(newline="")
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["bus", "timestamp_ns", "can_id", "data_hex"])
    for bus, ts, ident, data in rows:
        writer.writerow([bus, str(ts), "%08X" % ident, data.hex().upper()])
    path.write_text(buf.getvalue(), encoding="utf-8")


def main() -> None:
    DIST.mkdir(parents=True, exist_ok=True)
    tl = Timeline()
    expected: dict = {
        "data_gap_ns": DATA_GAP_NS,
        "control_gap_ns": CONTROL_GAP_NS,
        "scenarios": [],
    }

    def scenario(name: str) -> None:
        expected["scenarios"].append({"name": name, "first_row": len(tl.rows) + 2})

    # ------------------------------------------------------------------
    # S1: BAM, hand-written 15-byte payload spanning 3 packets.
    # Expected payload bytes are asserted literally by the verifier.
    # ------------------------------------------------------------------
    scenario("S1_bam_three_packets")
    bam_payload = bytes([0xA0, 0xA1, 0xA2, 0xA3, 0xA4, 0xA5, 0xA6,
                         0xB0, 0xB1, 0xB2, 0xB3, 0xB4, 0xB5, 0xB6, 0xB7])
    s1_size = len(bam_payload)          # 15 -> 3 packets
    s1_start = 1_000
    tl.at(BUS_A, s1_start, cm_id(SRC, GLOBAL), bam(s1_size, 3))
    s1_packet_lines = []
    for i in range(3):
        chunk = bam_payload[i * 7:(i + 1) * 7]
        tl.advance(BUS_A, 10, dt_id(SRC, GLOBAL), dt(i + 1, chunk))
        s1_packet_lines.append(len(tl.rows) + 1)
    expected["scenarios"][-1].update({
        "mode": "BAM", "bus": BUS_A, "src": SRC, "dst": GLOBAL,
        "app_pgn": APP_PGN, "length": s1_size, "packets": 3,
        "payload_hex": bam_payload.hex(),
        "packet_source_lines": s1_packet_lines,
        "state": "completed",
        "trace_cases": [
            {"start": 0, "end": 7, "lines": [s1_packet_lines[0]]},
            {"start": 6, "end": 9,
             "lines": [s1_packet_lines[0], s1_packet_lines[1]]},
            {"start": 7, "end": 15,
             "lines": [s1_packet_lines[1], s1_packet_lines[2]]},
        ],
    })

    # An ordinary frame interspersed between transfers; never reassembled.
    oid, obytes = ordinary_frame(0x40, GLOBAL, b"ORD1")
    tl.advance(BUS_A, 20, oid, obytes)

    # ------------------------------------------------------------------
    # S2: RTS with TWO CTS rounds (window sizes 2 then 1), identical DT
    # retransmission inside the first window, EOM ACK at the end.
    # ------------------------------------------------------------------
    scenario("S2_rts_two_cts_rounds_with_duplicate")
    rts_payload = bytes(range(16))           # 16 bytes -> 3 packets, last one padded
    s2_start = tl.t + 100
    tl.at(BUS_A, s2_start, cm_id(SRC, R1), rts(16, 3, 2))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(2, 1))       # round 1: packets 1..2
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, rts_payload[0:7]))
    dup_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, rts_payload[0:7]))  # duplicate
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(2, rts_payload[7:14]))
    cts2_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(1, 3))       # round 2: packet 3
    tl.advance(BUS_A, 10, dt_id(SRC, R1),
               dt(3, rts_payload[14:16]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), eom_ack(16, 3))
    expected["scenarios"][-1].update({
        "mode": "RTS", "bus": BUS_A, "src": SRC, "dst": R1,
        "app_pgn": APP_PGN, "length": 16, "packets": 3,
        "payload_hex": rts_payload.hex(), "state": "completed",
        "cts_lines": [None, cts2_line], "duplicate_line": dup_line,
        "window_sizes": [2, 1],
    })

    # ------------------------------------------------------------------
    # S3: same sender, two different receivers, strictly interleaved.
    # Channels must not cross; both complete.
    # ------------------------------------------------------------------
    scenario("S3_two_receivers_interleaved")
    p3 = bytes([0x30 + i for i in range(9)])   # 9 bytes -> 2 packets each
    s3_start = tl.t + 100
    tl.at(BUS_A, s3_start, cm_id(SRC, R1), rts(9, 2, 1))
    tl.advance(BUS_A, 5, cm_id(SRC, R2), rts(9, 2, 1))
    tl.advance(BUS_A, 5, cm_id(R1, SRC), cts(1, 1))
    tl.advance(BUS_A, 5, cm_id(R2, SRC), cts(1, 1))
    tl.advance(BUS_A, 5, dt_id(SRC, R1), dt(1, p3[0:7]))
    tl.advance(BUS_A, 5, dt_id(SRC, R2), dt(1, p3[0:7]))
    tl.advance(BUS_A, 5, cm_id(R1, SRC), cts(1, 2))
    tl.advance(BUS_A, 5, cm_id(R2, SRC), cts(1, 2))
    tl.advance(BUS_A, 5, dt_id(SRC, R1), dt(2, p3[7:9]))
    tl.advance(BUS_A, 5, dt_id(SRC, R2), dt(2, p3[7:9]))
    tl.advance(BUS_A, 5, cm_id(R1, SRC), eom_ack(9, 2))
    tl.advance(BUS_A, 5, cm_id(R2, SRC), eom_ack(9, 2))
    expected["scenarios"][-1].update({
        "channels": [
            {"mode": "RTS", "src": SRC, "dst": R1, "state": "completed",
             "payload_hex": p3.hex()},
            {"mode": "RTS", "src": SRC, "dst": R2, "state": "completed",
             "payload_hex": p3.hex()},
        ],
    })

    # ------------------------------------------------------------------
    # S4: same packet number with changed bytes -> transfer fails.
    # ------------------------------------------------------------------
    scenario("S4_same_seq_changed_bytes")
    s4_start = tl.t + 100
    tl.at(BUS_A, s4_start, cm_id(SRC, R1), rts(16, 3, 3))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(3, 1))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, rts_payload[0:7]))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, b"\xFF" * 7))  # changed
    expected["scenarios"][-1].update({
        "mode": "RTS", "src": SRC, "dst": R1, "state": "failed",
        "failure_code": "dt_seq_conflict",
    })

    # ------------------------------------------------------------------
    # S5: data packet outside the CTS window -> transfer fails.
    # ------------------------------------------------------------------
    scenario("S5_data_outside_window")
    s5_start = tl.t + 100
    tl.at(BUS_A, s5_start, cm_id(SRC, R1), rts(9, 2, 1))
    # No CTS: the sender starts anyway.
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, p3[0:7]))
    expected["scenarios"][-1].update({
        "mode": "RTS", "src": SRC, "dst": R1, "state": "failed",
        "failure_code": "dt_outside_window",
    })

    # ------------------------------------------------------------------
    # S6: all packets arrive, but the EOM ACK is wrong then missing.
    # The wrong ACK cannot publish; control timeout then fails the wait.
    # ------------------------------------------------------------------
    scenario("S6_wrong_then_missing_ack")
    s6_start = tl.t + 100
    tl.at(BUS_A, s6_start, cm_id(SRC, R1), rts(9, 2, 2))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(2, 1))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, p3[0:7]))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(2, p3[7:9]))
    bad_ack_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, cm_id(R1, SRC), eom_ack(8, 2))     # wrong byte count
    # Timeout fires exactly at last_packet_time + control_gap.  Last packet
    # was at s6_start+30; deadline = +50 => s6_start+80.
    oid2, obytes2 = ordinary_frame(0x41, GLOBAL, b"ORD2")
    tl.advance(BUS_A, 50 - 10, oid2, obytes2)               # at +80 -> timeout
    expected["scenarios"][-1].update({
        "mode": "RTS", "src": SRC, "dst": R1,
        "state": "timed_out", "failure_event": "timed_out",
        "bad_ack_line": bad_ack_line, "bad_ack_event": "ack_bad",
        "missing_ack": True,
    })

    # ------------------------------------------------------------------
    # S7: a legal new announcement replaces an unfinished RTS transfer;
    # the replacement transfer then completes normally.
    # ------------------------------------------------------------------
    scenario("S7_replacement_then_success")
    s7_start = tl.t + 100
    tl.at(BUS_A, s7_start, cm_id(SRC, R1), rts(16, 3, 2))  # never gets a CTS
    replaced_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, cm_id(SRC, R1), rts(9, 2, 1))    # replacement
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(1, 1))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, p3[0:7]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(1, 2))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(2, p3[7:9]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), eom_ack(9, 2))
    expected["scenarios"][-1].update({
        "replaced_state": "replaced", "replaced_line": replaced_line,
        "replacement": {"mode": "RTS", "src": SRC, "dst": R1,
                        "state": "completed", "payload_hex": p3.hex()},
    })

    # ------------------------------------------------------------------
    # S8: BAM timeout at exactly deadline equality, advanced by an
    # ordinary frame; then a normal BAM reuses the same channel.
    # ------------------------------------------------------------------
    scenario("S8_exact_deadline_equality_then_reuse")
    s8_payload = bytes([0x80 + i for i in range(10)])  # 10 bytes -> 2 packets
    s8_start = tl.t + 100
    tl.at(BUS_A, s8_start, cm_id(SRC, GLOBAL), bam(10, 2))
    tl.advance(BUS_A, 10, dt_id(SRC, GLOBAL), dt(1, s8_payload[0:7]))
    # Deadline of packet 2 = packet1 time + DATA_GAP_NS exactly.
    oid3, obytes3 = ordinary_frame(0x42, GLOBAL, b"ORD3")
    tl.advance(BUS_A, DATA_GAP_NS - 10, oid3, obytes3)  # exact equality -> timeout
    expected["scenarios"][-1].update({
        "first_state": "timed_out", "missing_packet": 2,
    })
    # Reuse: fresh BAM on the same channel completes.
    s8b_start = tl.t + 50
    tl.at(BUS_A, s8b_start, cm_id(SRC, GLOBAL), bam(10, 2))
    tl.advance(BUS_A, 10, dt_id(SRC, GLOBAL), dt(1, s8_payload[0:7]))
    tl.advance(BUS_A, 10, dt_id(SRC, GLOBAL), dt(2, s8_payload[7:10]))
    expected["scenarios"][-1].update({
        "reuse_state": "completed", "reuse_payload_hex": s8_payload.hex(),
    })

    # ------------------------------------------------------------------
    # S9: traffic on the OTHER bus must not advance this bus's deadline.
    # can-alpha waits for a CTS; can-beta frames pass, then the CTS still
    # arrives in time on can-alpha.
    # ------------------------------------------------------------------
    scenario("S9_other_bus_does_not_advance_time")
    s9_start = tl.t + 200
    tl.at(BUS_A, s9_start, cm_id(SRC, R1), rts(9, 2, 1))
    # Bus B traffic interleaves through the whole wait.  These frames must
    # not expire the bus-A transfer (its deadline is s9_start+CONTROL_GAP_NS):
    # they even pass beyond the deadline, because timeouts are evaluated per
    # bus only.
    for k in range(3):
        oidb, obytesb = ordinary_frame(0x50 + k, GLOBAL, b"BUS%d" % k)
        tl.at(BUS_B, s9_start + 10 + k * 10, oidb, obytesb)
    # CTS on bus A exactly one tick before the deadline fires.
    tl.at(BUS_A, s9_start + CONTROL_GAP_NS - 1, cm_id(R1, SRC), cts(1, 1))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, p3[0:7]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(1, 2))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(2, p3[7:9]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), eom_ack(9, 2))
    expected["scenarios"][-1].update({
        "mode": "RTS", "bus": BUS_A, "src": SRC, "dst": R1,
        "state": "completed", "payload_hex": p3.hex(),
    })

    # ------------------------------------------------------------------
    # S10: abort by the receiver with a verbatim reason code.
    # ------------------------------------------------------------------
    scenario("S10_receiver_abort")
    s10_start = tl.t + 100
    tl.at(BUS_A, s10_start, cm_id(SRC, R1), rts(9, 2, 1))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(1, 1))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, p3[0:7]))
    abort_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, cm_id(R1, SRC), abort(0x06))
    expected["scenarios"][-1].update({
        "mode": "RTS", "src": SRC, "dst": R1, "state": "aborted",
        "abort_reason": 0x06, "abort_line": abort_line,
    })

    # ------------------------------------------------------------------
    # S11: unsupported controls and orphans: pause CTS (count 0),
    # re-authorization CTS, unknown control byte, and an abort with no
    # matching transfer.
    # ------------------------------------------------------------------
    scenario("S11_unsupported_and_orphan_controls")
    s11_start = tl.t + 100
    tl.at(BUS_A, s11_start, cm_id(SRC, R1), rts(16, 3, 2))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(0, 1))          # pause unsupported
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(2, 0))          # start 0 re-auth
    unknown_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cm(0x77))           # unknown byte
    # The RTS is still alive; a proper CTS now succeeds and it completes.
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(2, 1))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(1, rts_payload[0:7]))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(2, rts_payload[7:14]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), cts(1, 3))
    tl.advance(BUS_A, 10, dt_id(SRC, R1), dt(3, rts_payload[14:16]))
    tl.advance(BUS_A, 10, cm_id(R1, SRC), eom_ack(16, 3))
    orphan_line = len(tl.rows) + 2
    tl.advance(BUS_A, 10, cm_id(R2, SRC), abort(0x09))       # no such transfer
    expected["scenarios"][-1].update({
        "pause_event": "cts_unsupported",
        "reauth_event": "cts_unsupported",
        "unknown_line": unknown_line, "unknown_event": "unsupported_control",
        "orphan_line": orphan_line, "orphan_event": "orphan_control",
        "transfer_state": "completed",
    })

    # ------------------------------------------------------------------
    # S12: EOF incomplete BAM (no timeout; file just ends) and an
    # identifier with the reserved/EDP bit set (rejected frame).
    # ------------------------------------------------------------------
    scenario("S12_eof_incomplete_and_reserved_bit")
    s12_start = tl.t + 100
    bad_id = can_id(6, 1, 0, 0xFE, 0xEE, 0x60)
    reserved_line = len(tl.rows) + 2
    tl.at(BUS_A, s12_start, bad_id, b"\xDE\xAD\xBE\xEF\x00\x00\x00\x00")
    tl.advance(BUS_A, 10, cm_id(SRC, GLOBAL), bam(16, 3))
    tl.advance(BUS_A, 10, dt_id(SRC, GLOBAL), dt(1, rts_payload[0:7]))
    # File ends here: packets 2..3 never arrive.
    expected["scenarios"][-1].update({
        "reserved_line": reserved_line, "reserved_event": "identifier_rejected",
        "eof_state": "eof_incomplete", "eof_missing": [2, 3],
    })

    capture_path = DIST / "j1939-capture.csv"
    write_capture(capture_path, tl.rows)

    # Bad-capture variants: each is a small standalone file whose defect must
    # reject the WHOLE file (the valid-looking prefix never becomes a batch).
    bad_dir = DIST / "bad"
    bad_dir.mkdir(exist_ok=True)

    def bad_file(name: str, header: list[str], body: list[list[str]]) -> None:
        buf = io.StringIO(newline="")
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(header)
        w.writerows(body)
        (bad_dir / name).write_text(buf.getvalue(), encoding="utf-8")

    good_head = ["bus", "timestamp_ns", "can_id", "data_hex"]
    prefix = [
        [BUS_A, "1000", "%08X" % cm_id(SRC, GLOBAL), bam(16, 3).hex().upper()],
        [BUS_A, "1010", "%08X" % dt_id(SRC, GLOBAL),
         dt(1, rts_payload[0:7]).hex().upper()],
    ]
    # Time goes backwards after a valid-looking prefix.
    bad_file("ok-prefix-but-bad-tail.csv", good_head,
             prefix + [[BUS_A, "999", "%08X" % dt_id(SRC, GLOBAL),
                        dt(2, rts_payload[7:14]).hex().upper()]])
    # can_id that is not exactly eight hex digits.
    bad_file("bad-can-id.csv", good_head,
             [[BUS_A, "1000", "123ABC", (b"\x00" * 8).hex().upper()]])
    # data_hex that does not represent exactly eight bytes.
    bad_file("short-data.csv", good_head,
             [[BUS_A, "1000", "%08X" % cm_id(SRC, R1), "0102"]])
    # Missing column (short record).
    bad_file("missing-column.csv", good_head,
             [[BUS_A, "1", "%08X" % cm_id(SRC, R1)]])
    # Extra column.
    bad_file("extra-column.csv", good_head,
             [[BUS_A, "1", "%08X" % cm_id(SRC, R1),
               (b"\x00" * 8).hex().upper(), "extra"]])
    # Empty bus.
    bad_file("empty-bus.csv", good_head,
             [["", "1", "%08X" % cm_id(SRC, R1),
               (b"\x00" * 8).hex().upper()]])
    # 29-bit overflow (nine hex digits with high bits set).
    bad_file("id-overflow.csv", good_head,
             [[BUS_A, "1", "20000000", (b"\x00" * 8).hex().upper()]])

    (DIST / "j1939-expected.json").write_text(
        json.dumps(expected, ensure_ascii=False, indent=2, sort_keys=True),
        encoding="utf-8")
    print("wrote %s (%d frames) and %d bad-capture fixtures"
          % (capture_path, len(tl.rows), len(list(bad_dir.glob("*.csv")))))


if __name__ == "__main__":
    main()
